use core::marker::PhantomData;

use reflection::def_pool::{upb_DefPool_Free, upb_DefPool_New, RawDefPool};
use reflection::message_def::RawMessageDef;
use reflection::upb_TextEncode;

use upb::MessagePtr;

/// A wrapper over a `upb_DefPool`.
///
/// This is an owning type and will automatically free the pool when
/// dropped.
pub struct DefPool {
    raw: RawDefPool,
}

impl Default for DefPool {
    fn default() -> Self {
        Self::new()
    }
}

impl DefPool {
    /// Allocates a new pool.
    #[inline]
    pub fn new() -> Self {
        // SAFETY: `upb_DefPool_New` has no preconditions.
        let raw = unsafe { upb_DefPool_New() }.expect("DefPool allocation failed");
        Self { raw }
    }

    /// Returns the internal NonNull representation of the pool.
    #[inline]
    pub(crate) fn raw(&self) -> RawDefPool {
        self.raw
    }
}

impl Drop for DefPool {
    fn drop(&mut self) {
        // SAFETY: The pointer was generated by upb_DefPool_New and hasn't been freed.
        unsafe { upb_DefPool_Free(self.raw) }
    }
}

/// A borrowed message descriptor tied to the lifetime of a DefPool. No drop implementation is
/// provided because this is not an owning type and cannot be individually freed.
#[derive(Copy, Clone)]
pub struct MessageDef<'pool> {
    raw: RawMessageDef,
    _marker: PhantomData<&'pool DefPool>,
}

impl<'pool> MessageDef<'pool> {
    /// # Safety
    /// The caller must guarantee `raw` was allocated by the pool providing the `'pool` lifetime.
    pub unsafe fn from_raw(raw: RawMessageDef) -> Self {
        Self { raw, _marker: PhantomData }
    }

    /// Returns the internal NonNull representation of the descriptor.
    #[inline]
    pub(crate) fn raw(&self) -> RawMessageDef {
        self.raw
    }
}

/// Returns a string of field number to value entries of a message.
///
/// # Safety
/// - `msg` must be legally dereferenceable.
pub unsafe fn text_encode<'pool, T>(
    msg: MessagePtr<T>,
    def: MessageDef<'pool>,
    ext_pool: Option<&DefPool>,
    options: u32,
) -> String {
    let msg = msg.raw();
    let def_raw = def.raw();
    let ext_pool_raw = ext_pool.map(|p| p.raw());

    // Only find out the length first to then allocate a buffer of the minimum size
    // needed.
    // SAFETY:
    // - `msg` is valid per safety requirements of this function.
    // - `def` is valid per safety requirements of this function.
    // - `ext_pool` is valid per safety requirements of this function.
    // - `buf` is null and `size` is 0.
    let min_len = unsafe {
        upb_TextEncode(msg, def_raw, ext_pool_raw, options as i32, core::ptr::null_mut(), 0)
    };
    assert!(min_len < isize::MAX as usize);

    // +1 for the trailing NULL
    let mut buf = vec![0u8; min_len + 1];

    // SAFETY:
    // - `msg`, `def`, `ext_pool` are valid per safety requirements of this function.
    // - `buf` is legally writable for `buf.len()` bytes.
    let written_len = unsafe {
        upb_TextEncode(msg, def_raw, ext_pool_raw, options as i32, buf.as_mut_ptr(), buf.len())
    };
    assert_eq!(min_len, written_len);

    // Drop the trailing NULL written by `upb_TextEncode`.
    buf.truncate(written_len);
    String::from_utf8_lossy(buf.as_slice()).into_owned()
}
